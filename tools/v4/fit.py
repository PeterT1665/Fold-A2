"""Learn every ladder bot's behaviour from games/*.json.

  python tools/v4/fit.py

For each decision of each bot: situation key (v4/keys.py) -> counts of fold / call / raise / check
and the raise sizes it used. Writes:
  opponents/clone_data.json  per-bot tables + field ('*'), used by opponents/clone.py
  v4/field_model.py          field-wide tables, used by the v4 bot for range updates and fold odds
"""
import glob, json, os, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "v4"))
from cards7 import parse, bucket, hand_class
from keys import pf_sbucket, pf_pos, pf_key, facing_bucket, post_key
from pf_table import PF

EXCLUDE = set(sys.argv[1:])  # names to leave out of the field tables (e.g. our own bot)


def new():
    return {"f": 0, "c": 0, "r": 0, "x": 0, "sz": [], "rb": [0, 0, 0, 0]}


def size_bin(size, allin):
    if allin or size >= 1.2:
        return 3
    return 0 if size < 0.45 else (1 if size < 0.8 else 2)


def replay(game, emit):
    names = game["names"]
    for h in game["hands"]:
        sm = h["seat_map"]
        n = len(sm)
        holes = {int(s): [parse(c) for c in v] for s, v in h["holes"].items()}
        contrib = [0] * n
        sbet = [0] * n
        nraises = 0
        board = []
        street = "preflop"
        for ev in h["events"]:
            t = ev["type"]
            if t == "blinds":
                for s, a in ((ev["sb_seat"], ev["sb"]), (ev["bb_seat"], ev["bb"])):
                    contrib[s] += a; sbet[s] += a
            elif t == "street":
                board = [parse(c) for c in ev["board"]]
                street = ev["street"]
                sbet = [0] * n; nraises = 0
            elif t == "action":
                s = ev["seat"]; kind = ev["action"]; amt = ev["amount"]
                cur = max(sbet)
                stack = 200 - contrib[s]
                to_call = min(cur - sbet[s], stack)
                pot = sum(contrib)
                name = names[sm[s]]
                hole = holes.get(s)
                if hole is not None:
                    if street == "preflop":
                        pct = PF[hand_class(*hole)][2]
                        key = pf_key(nraises, pf_pos(s, n), pf_sbucket(pct))
                        size = amt / 2 if kind == "raise" else None
                    else:
                        st = {"flop": 1, "turn": 2, "river": 3}[street]
                        key = post_key(st, facing_bucket(to_call, pot, nraises), bucket(hole, board))
                        if kind == "raise":
                            size = (amt - sbet[s]) / max(pot, 1) if to_call == 0 else (amt - cur) / max(pot + to_call, 1)
                        else:
                            size = None
                    a = {"fold": "f", "call": "c", "raise": "r", "check": "x"}[kind]
                    emit(name, key, a, size, amt >= 200 - contrib[s] + sbet[s] if kind == "raise" else False)
                if kind == "call":
                    contrib[s] += amt; sbet[s] += amt
                elif kind == "raise":
                    add = amt - sbet[s]
                    contrib[s] += add; sbet[s] = amt
                    nraises += 1


def main():
    files = [f for f in glob.glob(os.path.join(ROOT, "games", "*.json")) if os.path.basename(f) not in ("index.json", "game1.json")]
    tab = defaultdict(lambda: defaultdict(new))
    hands = defaultdict(int)

    def emit(name, key, a, size, allin):
        for who in (name, "*") if name not in EXCLUDE else (name,):
            d = tab[who][key]
            d[a] += 1
            if size is not None:
                d["rb"][size_bin(size, allin)] += 1
            if size is not None and len(d["sz"]) < 60:
                d["sz"].append(round(-1 if allin else size, 3))

    for f in files:
        g = json.load(open(f))
        if not isinstance(g, dict) or "names" not in g:
            continue
        replay(g, emit)
        for nm in g["names"]:
            hands[nm] += len(g["hands"])
    out = {nm: {k: v for k, v in t.items()} for nm, t in tab.items()}
    json.dump({"hands": hands, "tables": out}, open(os.path.join(ROOT, "opponents", "clone_data.json"), "w"))
    field = {k: (v["f"], v["c"], v["x"], *v["rb"]) for k, v in tab["*"].items()}
    with open(os.path.join(ROOT, "v4", "field_model.py"), "w") as fh:
        fh.write('"""Generated by tools/v4/fit.py from %d ladder games: key -> (fold, call, check, raise by size bin <0.45, <0.8, <1.2, bigger/all-in) counts."""\n' % len(files))
        fh.write("FIELD = {\n")
        for k in sorted(field):
            fh.write(f"    {k!r}: {field[k]},\n")
        fh.write("}\n")
    print(len(files), "games;", len(out) - 1, "bots;", len(field), "field keys")


if __name__ == "__main__":
    main()
