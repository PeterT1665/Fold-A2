"""Build v4/pf_table.py: per 169-class equity vs 1 and 3 random hands, and combo percentile (0 = best)."""
import os, random, sys
from multiprocessing import Pool
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "v4"))
from cards7 import evaluate, hand_class, RANKS

def rep(cls):
    r1, r2 = RANKS.index(cls[0]), RANKS.index(cls[1])
    if len(cls) == 2: return (r1, 13 + r2)
    if cls[2] == "s": return (r1, r2)
    return (r1, 13 + r2)

def eq(args):
    cls, nopp, n = args
    h = list(rep(cls)); rng = random.Random(cls + str(nopp))
    deck = [c for c in range(52) if c not in h]; s = 0.0
    for _ in range(n):
        d = rng.sample(deck, 5 + 2 * nopp); b = d[:5]
        me = evaluate(h + b); best = max(evaluate(d[5+2*i:7+2*i] + b) for i in range(nopp))
        s += 1 if me > best else (0.5 if me == best else 0)
    return s / n

if __name__ == "__main__":
    classes = sorted({hand_class(a, b) for a in range(52) for b in range(a + 1, 52)})
    with Pool(8) as p:
        e1 = p.map(eq, [(c, 1, 6000) for c in classes])
        e3 = p.map(eq, [(c, 3, 3000) for c in classes])
    E = {c: (a, b) for c, a, b in zip(classes, e1, e3)}
    combos = lambda c: 6 if len(c) == 2 else (4 if c[2] == "s" else 12)
    # rank by blend: heads-up equity matters most but multiway playability too
    order = sorted(classes, key=lambda c: -(0.6 * E[c][0] + 0.4 * E[c][1] * 1.9))
    cum = 0; pct = {}
    for c in order:
        pct[c] = (cum + combos(c) / 2) / 1326; cum += combos(c)
    with open(os.path.join(ROOT, "v4", "pf_table.py"), "w") as f:
        f.write('"""Generated by tools/v4/make_preflop.py. class -> (equity vs 1 random, vs 3 random, percentile 0=best)."""\n')
        f.write("PF = {\n")
        for c in order:
            f.write(f"    {c!r}: ({E[c][0]:.4f}, {E[c][1]:.4f}, {pct[c]:.4f}),\n")
        f.write("}\n")
    print(order[:30]); print(order[-10:])
